#!/usr/bin/env python3
"""Regenerate js/schedule.js from the league's public schedule page.

The app cannot ask the schedule site who plays whom at run time: the site
sends no cross-origin headers, so a browser on another origin is refused.
The fixtures are therefore shipped with the app, and this script is how
they get there. Run it at the start of a season and whenever the league
reschedules, then rebuild the image:

    python3 tools/update-schedule.py

It reads the schedule address from js/league.js (SCHEDULE_URL), walks the
page and the further pages it lazy-loads, and writes every game's date and
two teams. Nothing but the standard library is needed.
"""
import datetime
import html
import json
import pathlib
import re
import sys
import urllib.parse
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
LEAGUE = ROOT / 'js' / 'league.js'
OUT = ROOT / 'js' / 'schedule.js'

DAY = re.compile(r'<time[^>]*\bdatetime="(\d{4}-\d\d-\d\d)"')
TEAM = re.compile(r'<[^>]*\sdata-game-team\s*>.*?<p[^>]*>\s*(?:<a[^>]*>)?\s*([^<]+?)\s*<', re.S)
# The placeholder the page leaves for its next batch of games: where to get
# it, and the frame it must be asked for by name (without the Turbo-Frame
# header the site answers with the first page again).
MORE = re.compile(r'<turbo-frame[^>]*\bdata-append-frame-src-value="([^"]+)"[^>]*\bid="([^"]+)"')


def fetch(url, frame=None):
    headers = {'User-Agent': 'Mozilla/5.0', 'Accept': 'text/html'}
    if frame:
        headers['Turbo-Frame'] = frame
    req = urllib.request.Request(url, headers=headers)
    with urllib.request.urlopen(req, timeout=30) as res:
        return res.read().decode('utf-8', 'replace')


def games_in(page):
    """(date, team, team) for each game on one page, in page order."""
    marks = [(m.start(), 'day', m.group(1)) for m in DAY.finditer(page)]
    marks += [(m.start(), 'team', html.unescape(m.group(1))) for m in TEAM.finditer(page)]
    day, side, out = None, None, []
    for _, kind, value in sorted(marks):
        if kind == 'day':
            day, side = value, None
        elif side is None:
            side = value
        else:
            if day is None:
                sys.exit('A game appeared before any date: the page layout has changed.')
            out.append((day, side, value))
            side = None
    if side is not None:
        sys.exit('A game with only one team (%s): the page layout has changed.' % side)
    return out


def main():
    league = LEAGUE.read_text(encoding='utf-8')
    found = re.search(r"SCHEDULE_URL:\s*'([^']+)'", league)
    if not found:
        sys.exit('No SCHEDULE_URL in %s' % LEAGUE)
    url, frame, games, seen = found.group(1), None, [], set()
    while url and url not in seen:
        seen.add(url)
        page = fetch(url, frame)
        games += games_in(page)
        nxt = MORE.search(page)
        url = urllib.parse.urljoin(url, html.unescape(nxt.group(1))) if nxt else None
        frame = nxt.group(2) if nxt else None
    if not games:
        sys.exit('No games found: the page layout has changed.')
    if len(set(games)) != len(games):
        sys.exit('The same game came back twice: the paging has changed.')
    games.sort(key=lambda g: g[0])

    teams = sorted({t for g in games for t in g[1:]})
    unknown = [t for t in teams if t not in league]
    for t in unknown:
        print('warning: %r is on the schedule but not spelled that way in js/league.js' % t)

    lines = ['    [%s, %s, %s]' % tuple(json.dumps(x, ensure_ascii=False) for x in g) for g in games]
    OUT.write_text(
        "/* Generated by tools/update-schedule.py from League.SCHEDULE_URL on %s.\n"
        " * Do not edit by hand: run the script again when the league reschedules.\n"
        " * Each row is one game: the date it is played, and the two teams. */\n"
        "(function (global) {\n"
        "  'use strict';\n"
        "\n"
        "  global.League.GAMES = [\n%s\n  ];\n"
        "})(window);\n" % (datetime.date.today().isoformat(), ',\n'.join(lines)),
        encoding='utf-8')
    print('%d games, %d teams, %s to %s -> %s' % (
        len(games), len(teams), games[0][0], games[-1][0], OUT.relative_to(ROOT)))
    return 1 if unknown else 0


if __name__ == '__main__':
    sys.exit(main())
